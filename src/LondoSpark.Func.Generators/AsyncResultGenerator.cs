using System.Linq;

using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace LondoSpark.Func.Generators;

/// <summary>Completes a struct marked <c>[AsyncResult&lt;TFailure&gt;]</c> as a result type that async methods can return.</summary>
/// <remarks>
/// <code>
/// [AsyncResult&lt;CustomerError&gt;]
/// public readonly partial struct Registration&lt;T&gt;;
/// </code>
/// becomes a union over <c>Result&lt;T, CustomerError&gt;</c>'s <c>Success</c> and <c>Failure</c> cases that converts to
/// and from that result, can be awaited, and has a builder, so <c>async Registration&lt;Customer&gt; Register(...)</c>
/// compiles. C# accepts only task-like types with one type parameter, which is why a result needs this.
/// </remarks>
[Generator(LanguageNames.CSharp)]
public sealed class AsyncResultGenerator : IIncrementalGenerator
{
    private const string AttributeMetadataName = "LondoSpark.Func.AsyncResultAttribute`1";

    internal static readonly DiagnosticDescriptor StructShape = new(
        "LSF0103",
        "Async result type has the wrong shape",
        "'{0}' must be a top-level partial struct with exactly one type parameter to be an async result type",
        "Usage",
        DiagnosticSeverity.Error,
        isEnabledByDefault: true,
        description: "C# accepts only task-like types with one type parameter, the success type; the attribute supplies the failure type.");

    private static readonly SymbolDisplayFormat TypeFormat =
        SymbolDisplayFormat.FullyQualifiedFormat.AddMiscellaneousOptions(
            SymbolDisplayMiscellaneousOptions.IncludeNullableReferenceTypeModifier);

    /// <inheritdoc/>
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var types = context.SyntaxProvider.ForAttributeWithMetadataName(
            AttributeMetadataName,
            static (node, _) => node is StructDeclarationSyntax,
            static (attributeContext, _) => Describe(attributeContext));

        context.RegisterSourceOutput(types, static (output, type) =>
        {
            if (type.Problem is { } problem)
            {
                output.ReportDiagnostic(Diagnostic.Create(StructShape, problem.ToLocation(), type.Name));
                return;
            }

            output.AddSource($"{type.HintName}.AsyncResult.g.cs", Render(type));
        });
    }

    private static AsyncResultType Describe(GeneratorAttributeSyntaxContext context)
    {
        var symbol = (INamedTypeSymbol)context.TargetSymbol;
        var declaration = (StructDeclarationSyntax)context.TargetNode;
        var failure = context.Attributes.First().AttributeClass!.TypeArguments[0];

        var shapeIsValid = symbol.ContainingType is null
            && symbol.TypeParameters.Length == 1
            && declaration.Modifiers.Any(SyntaxKind.PartialKeyword);

        return new AsyncResultType(
            symbol.ContainingNamespace.IsGlobalNamespace ? null : symbol.ContainingNamespace.ToDisplayString(),
            symbol.Name,
            symbol.TypeParameters.FirstOrDefault()?.Name ?? "T",
            symbol.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat).Replace("global::", string.Empty).Replace('<', '_').Replace('>', '_'),
            failure.ToDisplayString(TypeFormat),
            symbol.DeclaredAccessibility == Accessibility.Public ? "public" : "internal",
            shapeIsValid ? null : LocationInfo.From(declaration.Identifier.GetLocation()));
    }

    private static string Render(AsyncResultType type)
    {
        var name = type.Name;
        var t = type.TypeParameter;
        var self = $"{name}<{t}>";
        var result = $"global::LondoSpark.Func.Result<{t}, {type.Failure}>";
        var header = type.Namespace is { } ns ? $"namespace {ns};\n\n" : string.Empty;

        return $$"""
            // <auto-generated/>
            #nullable enable

            {{header}}/// <summary>A <see cref="global::LondoSpark.Func.Result{TSuccess, TFailure}"/> with a fixed failure type, which <see langword="async"/> methods can return.</summary>
            /// <remarks>
            /// Inside <c>async {{name}}&lt;{{t}}&gt;</c>, <c>await</c> unwraps a successful result and returns any failure from the method;
            /// <c>await failure(error);</c> fails it. The method runs synchronously. Match it with the result's
            /// <c>Success</c> and <c>Failure</c> cases, or convert it to the result implicitly.
            /// </remarks>
            [global::System.Runtime.CompilerServices.Union]
            [global::System.Runtime.CompilerServices.AsyncMethodBuilder(typeof({{name}}MethodBuilder<>))]
            partial struct {{self}} : global::System.IEquatable<{{self}}>, global::LondoSpark.Func.IShortCircuit<{{self}}>
            {
                private readonly {{result}} _result;

                private {{name}}({{result}} result) => _result = result;

                /// <summary>Creates the successful case.</summary>
                /// <param name="value">The successful case.</param>
                public {{name}}({{result}}.Success value) => _result = new {{result}}(value);

                /// <summary>Creates the failed case.</summary>
                /// <param name="value">The failed case.</param>
                public {{name}}({{result}}.Failure value) => _result = new {{result}}(value);

                /// <summary>Gets the boxed active case.</summary>
                public object Value => _result.Value;

                /// <summary>Gets whether this value contains a case; <see langword="false"/> only for <see langword="default"/>.</summary>
                public bool HasValue => _result.HasValue;

                /// <summary>Gets the successful case when this value contains one.</summary>
                /// <param name="value">Receives the successful case.</param>
                /// <returns><see langword="true"/> when this value is a success.</returns>
                public bool TryGetValue(out {{result}}.Success value) => _result.TryGetValue(out value);

                /// <summary>Gets the failed case when this value contains one.</summary>
                /// <param name="value">Receives the failed case.</param>
                /// <returns><see langword="true"/> when this value is a failure.</returns>
                public bool TryGetValue(out {{result}}.Failure value) => _result.TryGetValue(out value);

                /// <summary>Gets the wrapped result, for query syntax and the result's operations.</summary>
                /// <returns>The result.</returns>
                public {{result}} AsResult() => _result;

                /// <summary>Lets <c>await</c> unwrap the success inside a short-circuiting async method.</summary>
                /// <returns>An awaiter that completes synchronously.</returns>
                [global::System.ComponentModel.EditorBrowsable(global::System.ComponentModel.EditorBrowsableState.Never)]
                public global::LondoSpark.Func.ResultAwaiter<{{t}}, {{type.Failure}}> GetAwaiter() => _result.GetAwaiter();

                /// <summary>Wraps a result.</summary>
                /// <param name="result">The result.</param>
                public static implicit operator {{self}}({{result}} result) => new(result);

                /// <summary>Unwraps the result.</summary>
                /// <param name="value">The value.</param>
                public static implicit operator {{result}}({{self}} value) => value._result;

                /// <summary>Completes a prelude <c>success(value)</c>.</summary>
                /// <param name="value">The pending success.</param>
                public static implicit operator {{self}}(global::LondoSpark.Func.Prelude.Succeeded<{{t}}> value) => new(({{result}})value);

                /// <summary>Completes a prelude <c>failure(error)</c>.</summary>
                /// <param name="value">The pending failure.</param>
                public static implicit operator {{self}}(global::LondoSpark.Func.Prelude.Failed<{{type.Failure}}> value) => new(({{result}})value);

                static bool global::LondoSpark.Func.IShortCircuit<{{self}}>.TryShortCircuit(global::LondoSpark.Func.ShortCircuitException exception, out {{self}} value)
                {
                    if (exception is global::LondoSpark.Func.ShortCircuitException<{{type.Failure}}> failed)
                    {
                        value = new(new {{result}}.Failure(failed.Failure));
                        return true;
                    }

                    value = new(default({{result}}));
                    return false;
                }

                /// <inheritdoc/>
                public bool Equals({{self}} other) => _result.Equals(other._result);

                /// <inheritdoc/>
                public override bool Equals(object? obj) => obj is {{self}} other && Equals(other);

                /// <inheritdoc/>
                public override int GetHashCode() => _result.GetHashCode();

                /// <summary>Determines whether two values are equal.</summary>
                public static bool operator ==({{self}} left, {{self}} right) => left.Equals(right);

                /// <summary>Determines whether two values differ.</summary>
                public static bool operator !=({{self}} left, {{self}} right) => !left.Equals(right);

                /// <inheritdoc/>
                public override string ToString() => _result.ToString();
            }

            /// <summary>Builds <c>async {{name}}&lt;{{t}}&gt;</c> methods.</summary>
            [global::System.ComponentModel.EditorBrowsable(global::System.ComponentModel.EditorBrowsableState.Never)]
            [global::System.Diagnostics.CodeAnalysis.SuppressMessage("Design", "CA1000:Do not declare static members on generic types", Justification = "The async method builder pattern requires a static Create.")]
            {{type.Accessibility}} struct {{name}}MethodBuilder<{{t}}>
            {
                private global::LondoSpark.Func.ResultMethodBuilder<{{t}}, {{type.Failure}}> _inner;

                /// <summary>Creates a builder.</summary>
                public static {{name}}MethodBuilder<{{t}}> Create() => default;

                /// <summary>Gets the value the method produced.</summary>
                public readonly {{self}} Task => _inner.Task;

                /// <summary>Runs the method to completion.</summary>
                public readonly void Start<TStateMachine>(ref TStateMachine stateMachine)
                    where TStateMachine : global::System.Runtime.CompilerServices.IAsyncStateMachine =>
                    _inner.Start(ref stateMachine);

                /// <summary>Not used: the method never suspends.</summary>
                public readonly void SetStateMachine(global::System.Runtime.CompilerServices.IAsyncStateMachine stateMachine) =>
                    _inner.SetStateMachine(stateMachine);

                /// <summary>Records the success the method returned.</summary>
                public void SetResult({{t}} result) => _inner.SetResult(result);

                /// <summary>Records the failure for a short-circuit, or the error for anything else.</summary>
                public void SetException(global::System.Exception exception) => _inner.SetException(exception);

                /// <summary>Rejects an await that would suspend the method.</summary>
                public readonly void AwaitOnCompleted<TAwaiter, TStateMachine>(ref TAwaiter awaiter, ref TStateMachine stateMachine)
                    where TAwaiter : global::System.Runtime.CompilerServices.INotifyCompletion
                    where TStateMachine : global::System.Runtime.CompilerServices.IAsyncStateMachine =>
                    _inner.AwaitOnCompleted(ref awaiter, ref stateMachine);

                /// <summary>Rejects an await that would suspend the method.</summary>
                public readonly void AwaitUnsafeOnCompleted<TAwaiter, TStateMachine>(ref TAwaiter awaiter, ref TStateMachine stateMachine)
                    where TAwaiter : global::System.Runtime.CompilerServices.ICriticalNotifyCompletion
                    where TStateMachine : global::System.Runtime.CompilerServices.IAsyncStateMachine =>
                    _inner.AwaitUnsafeOnCompleted(ref awaiter, ref stateMachine);
            }

            """;
    }

    private sealed record AsyncResultType(
        string? Namespace,
        string Name,
        string TypeParameter,
        string HintName,
        string Failure,
        string Accessibility,
        LocationInfo? Problem);
}
